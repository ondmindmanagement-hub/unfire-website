const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '../audio/maletin/index.html'), 'utf8');
const begin = html.indexOf('  function createStage(canvas) {');
assert.ok(begin > 0, 'Secondary product-stage WebGL exists');
assert.equal(html.indexOf('  function createStage(canvas) {', begin + 1), -1);
const block = html.slice(begin, begin + 3400);
assert.match(html.slice(0, begin), /window\.__UNFIRE_AUTOCALIB=detect\(\)/);
assert.match(block, /stageBudget = window\.__UNFIRE_AUTOCALIB/);
assert.match(block, /stageCompact = stageBudget\.tier === 'compact'/);
assert.match(block, /stageBalanced = stageBudget\.tier === 'balanced'/);
assert.match(block, /stageDpr = Math\.min\(window\.devicePixelRatio \|\| 1, stageBudget\.maxDpr \|\| 1\.5\)/);
