#!/usr/bin/env python3
"""Single source of truth for the PHYSICAL Hyperwave 2000 choreography.
Derived from the physically-corrected digital timeline in audio/hyperwave/index.html (T = 0..4, t = T / 0.85 s).
Writes choreography.json (real units: mm, degrees, seconds) and firmware/choreography.h.
Run: python3 gen_choreography.py"""
import json, math, pathlib
SPEED = 0.85
def s(T): return round(T / SPEED, 4)
# Each axis: list of segments (t0_s, t1_s, from, to, profile). Profiles: 'mj' = minimum-jerk quintic, 'dec' = cubic ease-out, 'lin' = linear.
AX = {}
AX['canopy_deg']   = dict(unit='deg', motor='canopy',  segs=[(s(0.30), s(0.95), 0.0, 91.7, 'mj'), (s(3.55), s(4.00), 91.7, 95.1, 'mj')], vmax=260, note='geared drive + torsion counterbalance; latch released at t=0.16 s')
AX['tray_cam']     = dict(unit='turn', motor='tray',   segs=[(s(1.00), s(1.70), 0.0, 0.5, 'mj')], vmax=1.5, note='one cam plate: first quarter-turn lifts 14 mm, second advances 8 mm; also flips the wheels up')
AX['key_cam_deg']  = dict(unit='deg', motor='keys',    segs=[(s(1.30), s(1.55 + 24 * 0.022), 0.0, 180.0, 'mj')], vmax=600, note='25-lobe camshaft, lobes phased 7.5 deg apart; dwell holds keys up')
AX['panel_front_mm'] = dict(unit='mm', motor='panelF', segs=[(s(2.00), s(2.35), 0.0, 23.0, 'dec')], vmax=180, note='lead screw (8 mm lead), scissor only guides')
AX['panel_rear_mm']  = dict(unit='mm', motor='panelR', segs=[(s(2.00), s(2.35), 0.0, 23.0, 'dec'), (s(2.35), s(2.70), 23.0, 38.9, 'mj')], vmax=180, note='rear rises 15.9 mm more = 0.20 rad tilt over 80 mm')
AX['knob_bar_mm']  = dict(unit='mm', motor='knobs',   segs=[(s(2.20), s(2.50 + 8 * 0.07), 0.0, 21.5, 'lin')], vmax=40, note='lost-motion slots 1.75 mm apart stagger the 9 knobs; 7.5 mm-pitch helix turns each knob once')
# speaker arms (computed from the corrected pod path; root at x=208 mm, y=47 mm; wrist 15 mm inside the pod)
def podpath(T):
    def mj(u): return u ** 3 * (u * (u * 6 - 15) + 10)
    K = [(0, (2.66, 0.5, 0, 0)), (1.0, None), (1.4, (2.76, 0.5, 0, 0)), (3.0, None), (3.45, (2.96, 0.66, 0, 0)), (3.95, (3.08, 1.02, 0.15, -math.pi / 2))]
    pts = []; last = None
    for t, v in K: last = v if v is not None else last; pts.append((t, last))
    i = 0
    while i < len(pts) - 1 and T > pts[i + 1][0]: i += 1
    A, B = pts[i], pts[min(i + 1, len(pts) - 1)]
    u = 1 if (B[0] == A[0] or T >= B[0]) else (0 if T <= A[0] else mj((T - A[0]) / (B[0] - A[0])))
    x, y, z, yaw = [a + (b - a) * u for a, b in zip(A[1], B[1])]
    wx, wy, wz = x - 0.15 * math.cos(yaw), y, z + 0.15 * math.sin(yaw)
    dx, dy = wx - 2.08, wy - 0.47
    return math.hypot(dx, dy) * 100, math.degrees(math.atan2(dy, dx)), -math.degrees(yaw)
tab = [(round(i * 0.01, 2),) + podpath(i * 0.01 * SPEED) for i in range(0, int(4 / SPEED / 0.01) + 2)]
for side in ('L', 'R'):
    AX[f'arm{side}_len_mm'] = dict(unit='mm', motor=f'arm{side}len', table=[(t, round(L, 3)) for t, L, e, y in tab], vmax=160, note='4-stage telescope, 34 mm tubes, capacity 127 mm')
    AX[f'arm{side}_elev_deg'] = dict(unit='deg', motor=f'arm{side}el', table=[(t, round(e, 3)) for t, L, e, y in tab], vmax=60, note='worm-geared elevation (self-locking)')
    AX[f'pod{side}_yaw_deg'] = dict(unit='deg', motor=f'pod{side}yaw', table=[(t, round(y, 3)) for t, L, e, y in tab], vmax=320, note='wrist turntable in pod; tilt is passive (parallel link)')
INTERLOCKS = [
 ('panel_front_mm', '>', 0.2, 'canopy_deg', '>=', 85.0, 'panel may not rise until canopy is at least 85 deg open'),
 ('tray_cam', '>', 0.002, 'canopy_deg', '>=', 60.0, 'keyboard tray may not lift until canopy is clear'),
 ('canopy_deg', '<', 89.0, 'armL_len_mm', '<=', 44.5, 'canopy may not close unless left pod is docked'),
 ('canopy_deg', '<', 89.0, 'armR_len_mm', '<=', 44.5, 'canopy may not close unless right pod is docked'),
 ('canopy_deg', '<', 89.0, 'panel_rear_mm', '<=', 0.5, 'canopy may not close unless panel is fully down'),
 ('canopy_deg', '<', 89.0, 'tray_cam', '<=', 0.002, 'canopy may not close unless tray is stowed'),
]
out = {'source': 'audio/hyperwave/index.html (physically corrected), SPEED 0.85', 'duration_s': round(4 / SPEED, 4), 'axes': AX, 'interlocks': INTERLOCKS}
here = pathlib.Path(__file__).parent
(here / 'choreography.json').write_text(json.dumps(out, indent=1))
h = ['// GENERATED by gen_choreography.py — do not edit by hand.', '#pragma once', '#include <stdint.h>', 'namespace hw {',
     'enum Profile : uint8_t { MJ = 0, DEC = 1, LIN = 2 };', 'struct Seg { float t0, t1, a, b; Profile p; };', 'struct Pt { float t, v; };',
     f'constexpr float SEQ_DURATION = {out["duration_s"]}f;']
names = list(AX.keys())
h.append(f'constexpr int AXES = {len(names)};')
h.append('enum Axis : uint8_t { ' + ', '.join(n.upper() for n in names) + ' };')
for n in names:
    a = AX[n]
    if 'segs' in a:
        h.append(f'constexpr Seg {n.upper()}_SEG[] = {{ ' + ', '.join(f'{{{t0}f, {t1}f, {f0}f, {f1}f, {dict(mj="MJ", dec="DEC", lin="LIN")[p]}}}' for t0, t1, f0, f1, p in a['segs']) + ' };')
    else:
        h.append(f'constexpr Pt {n.upper()}_TAB[] = {{ ' + ', '.join(f'{{{t}f, {v}f}}' for t, v in a['table']) + ' };')
h.append('struct AxisDef { const char* name; const Seg* seg; uint8_t nseg; const Pt* tab; uint16_t ntab; float vmax; };')
rows = []
for n in names:
    a = AX[n]
    if 'segs' in a: rows.append(f'{{"{n}", {n.upper()}_SEG, {len(a["segs"])}, nullptr, 0, {float(a["vmax"])}f}}')
    else: rows.append(f'{{"{n}", nullptr, 0, {n.upper()}_TAB, {len(a["table"])}, {float(a["vmax"])}f}}')
h.append('constexpr AxisDef AXIS_DEFS[AXES] = { ' + ', '.join(rows) + ' };')
h.append('struct Interlock { uint8_t axis; char op; float thr; uint8_t guard; char gop; float gthr; const char* why; };')
il = [f'{{{a1.upper()}, \'{op}\', {t1}f, {a2.upper()}, \'{gop[0]}\', {t2}f, "{why}"}}' for a1, op, t1, a2, gop, t2, why in INTERLOCKS]
h.append(f'constexpr int NINTERLOCKS = {len(il)};')
h.append('constexpr Interlock INTERLOCKS[NINTERLOCKS] = { ' + ', '.join(il) + ' };')
h.append('}  // namespace hw')
(here / 'firmware').mkdir(exist_ok=True)
(here / 'firmware' / 'choreography.h').write_text('\n'.join(h) + '\n')
print('axes', len(names), 'duration', out['duration_s'], 's')
